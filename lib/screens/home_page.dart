Future<void> _verifyPremiumDowngrade() async {
  if (_isVerifyingPremiumDowngrade) return;
  _isVerifyingPremiumDowngrade = true;

  try {
    await Future.delayed(const Duration(milliseconds: 900));
    await Purchases.invalidateCustomerInfoCache();
    final customerInfo = await Purchases.getCustomerInfo();
    final isPremium = customerInfo.entitlements.active.containsKey('premium');
    debugPrint(
      '[HomePage] verify premium downgrade isPremium=$isPremium active=${customerInfo.entitlements.active.keys.toList()}',
    );

    if (!mounted) return;
    setState(() {
      _isPremium = isPremium;
      _hasLoadedPremium = true;
    });

    if (isPremium) {
      await _loadProfileTitleIfNeeded();
      await _loadStreakInsights();
    }
  } catch (e) {
    debugPrint('[HomePage] verify premium downgrade error=$e');
  } finally {
    _isVerifyingPremiumDowngrade = false;
  }
}


Future<void> _updateHomeWidgetFromCurrentState() async {
  final totalBudget = _totalBudget;
  final remaining = _remainingBudgetCache;

  final categoryCandidates = _categorySummariesCache
      .where((category) => (category['budget'] as int) > 0)
      .toList();

  final dangerCategories = categoryCandidates
      .where((category) {
        final remaining = category['remaining'] as int;
        final usageRate = category['usageRate'] as double;
        return remaining < 0 || usageRate >= 0.75;
      })
      .toList()
    ..sort((a, b) {
      final aRemaining = a['remaining'] as int;
      final bRemaining = b['remaining'] as int;
      final aUsageRate = a['usageRate'] as double;
      final bUsageRate = b['usageRate'] as double;

      final byRemaining = aRemaining.compareTo(bRemaining);
      if (byRemaining != 0) return byRemaining;

      return bUsageRate.compareTo(aUsageRate);
    });

  final widgetCategories = <Map<String, dynamic>>[
    ...dangerCategories.take(2),
  ];

  if (widgetCategories.length < 2) {
    final randomNormalCategories = categoryCandidates
        .where((category) => !widgetCategories.any(
              (selected) => selected['name'] == category['name'],
            ))
        .toList()
      ..shuffle(Random());

    widgetCategories.addAll(
      randomNormalCategories.take(2 - widgetCategories.length),
    );
  }

  await WidgetSyncService.updateRemainingBudget(
    remaining,
    totalBudget: totalBudget,
    dangerCategories: widgetCategories.map(
          (category) => WidgetDangerCategory(
            name: category['name'] as String,
            remaining: category['remaining'] as int,
            badge: category['badge'] as String,
            budget: category['budget'] as int,
          ),
        ).toList(),
  );
}

