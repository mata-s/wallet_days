  Future<Expense?> _editExpense(Expense expense) async {
  final result = await Navigator.push(
    context,
    MaterialPageRoute(
      builder: (_) => AddExpensePage(initialExpense: expense),
    ),
  );

  if (result == true) {
    await _loadInitialData();

    for (final item in _expenses) {
      if (item.id == expense.id) return item;
    }
  }

  return null;
}

Future<bool> _deleteExpense(Expense expense) async {
  final shouldDelete = await showDialog<bool>(
    context: context,
    builder: (dialogContext) {
      return AlertDialog(
        title: Text(_t('支出を削除しますか？', 'Delete this expense?')),
        content: Text(_t('${expense.storeName} の支出を削除します。', 'Delete the expense from ${expense.storeName}.')),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(dialogContext, false),
            child: Text(_t('キャンセル', 'Cancel')),
          ),
          TextButton(
            onPressed: () => Navigator.pop(dialogContext, true),
            child: Text(_t('削除', 'Delete')),
          ),
        ],
      );
    },
  );

  if (shouldDelete != true) return false;

  await IsarService.deleteExpense(expense.id);
  await flutterLocalNotificationsPlugin.cancel(id: expense.id);
  if (_isPremium) {
    await ExpenseSyncService.deleteExpense(expense.id);
  }
  await _loadInitialData();
  return true;
}


