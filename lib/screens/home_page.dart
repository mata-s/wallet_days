  Future<void> _loadStreakInsights() async {
    final user = _currentUser;
    if (!_isPremium || user == null) {
      if (!mounted) return;
      setState(() {
        _streakBestPercent = null;
        _streakCurrentPercent = null;
        _streakCohortPercent = null;
        _streakNextGoal = null;
        _streakType = null;
        _streakNextStepMessage = null;
        _streakEncouragementMessage = null;
      });
      return;
    }

    if (mounted) {
      setState(() {
        _isLoadingStreakInsights = true;
      });
    }

    try {
      final supabase = Supabase.instance.client;

      final latestHistory = await supabase
          .from('budget_histories')
          .select('best_streak, streak, created_at')
          .eq('user_id', user.id)
          .order('created_at', ascending: false)
          .limit(1)
          .maybeSingle();

      if (latestHistory == null) {
        if (!mounted) return;
        setState(() {
          _streakBestPercent = null;
          _streakCurrentPercent = null;
          _streakCohortPercent = null;
          _streakNextGoal = null;
          _streakType = null;
          _streakNextStepMessage = null;
          _streakEncouragementMessage = null;
          _isLoadingStreakInsights = false;
        });
        return;
      }

      final bestStreak = (latestHistory['best_streak'] as int?) ?? 0;
      debugPrint('streak latestHistory=$latestHistory');
      debugPrint('streak values bestStreak=$bestStreak currentStreak=${latestHistory['streak']}');
      final currentStreak = (latestHistory['streak'] as int?) ?? 0;
      debugPrint('streak latestHistory=$latestHistory');
      debugPrint('streak values bestStreak=$bestStreak currentStreak=$currentStreak');

      final profile = await supabase
          .from('profiles')
          .select('created_at')
          .eq('id', user.id)
          .maybeSingle();

      String? cohortSegment;
      final profileCreatedAt = profile?['created_at'] as String?;
      if (profileCreatedAt != null && profileCreatedAt.isNotEmpty) {
        final parsed = DateTime.tryParse(profileCreatedAt)?.toLocal();
        if (parsed != null) {
          final month = parsed.month.toString().padLeft(2, '0');
          cohortSegment = 'cohort:${parsed.year}-$month';
        }
      }

      final distributionRows = await supabase
          .from('user_metric_distributions')
          .select('metric_key, segment_key, metric_value, user_count, sample_size')
          .inFilter('metric_key', ['best_streak', 'current_streak']);
      debugPrint('streak distributionRows count=${distributionRows.length}');
      debugPrint('streak distributionRows=$distributionRows');

      final bestRows = distributionRows
          .where((row) => row['metric_key'] == 'best_streak' && row['segment_key'] == 'all')
          .cast<Map<String, dynamic>>()
          .toList()
        ..sort((a, b) => _toInt(a['metric_value'])
            .compareTo(_toInt(b['metric_value'])));
      debugPrint('streak bestRows=$bestRows');

      final currentRows = distributionRows
          .where((row) => row['metric_key'] == 'current_streak' && row['segment_key'] == 'all')
          .cast<Map<String, dynamic>>()
          .toList()
        ..sort((a, b) => _toInt(a['metric_value'])
            .compareTo(_toInt(b['metric_value'])));
      debugPrint('streak currentRows=$currentRows');

      final cohortRows = cohortSegment == null
          ? <Map<String, dynamic>>[]
          : distributionRows
              .where((row) =>
                  row['metric_key'] == 'current_streak' &&
                  row['segment_key'] == cohortSegment)
              .cast<Map<String, dynamic>>()
              .toList()
            ..sort((a, b) => _toInt(a['metric_value'])
                .compareTo(_toInt(b['metric_value'])));
      debugPrint('streak cohortSegment=$cohortSegment');
      debugPrint('streak cohortRows=$cohortRows');

      final bestPercent = _calculateTopPercent(value: bestStreak, rows: bestRows);
      final currentPercent = _calculateTopPercent(value: currentStreak, rows: currentRows);
      final cohortPercent = _calculateTopPercent(value: currentStreak, rows: cohortRows);
      debugPrint(
        'streak percents best=$bestPercent '
        'current=$currentPercent '
        'cohort=$cohortPercent',
      );

      final displayBestPercent = _shouldShowPercent(bestPercent) ? bestPercent : null;
      final displayCurrentPercent = _shouldShowPercent(currentPercent) ? currentPercent : null;
      final displayCohortPercent = _shouldShowPercent(cohortPercent) ? cohortPercent : null;

      final percentMessage = _buildPercentMessage(currentPercent);
      final cohortMessage = _buildCohortMessage(
        percent: cohortPercent,
        isPercentVisible: displayCohortPercent != null,
      );
      final nextRankUpMessage = _buildNextRankUpMessage(
        currentStreak: currentStreak,
        rows: currentRows,
      );
      final nextCohortRankUpMessage = _buildNextCohortRankUpMessage(
        currentStreak: currentStreak,
        rows: cohortRows,
      );
      final shouldPrioritizeCohort =
          displayCurrentPercent == null && displayCohortPercent != null;


      if (!mounted) return;
      setState(() {
        _streakBestPercent = displayBestPercent;
        _streakCurrentPercent = displayCurrentPercent;
        _streakCohortPercent = displayCohortPercent;
        _streakNextGoal = null;
        _streakType = _deriveStreakType(
          bestStreak: bestStreak,
          currentStreak: currentStreak,
        );
        _streakNextStepMessage = shouldPrioritizeCohort
            ? (nextCohortRankUpMessage ??
                cohortMessage ??
                _deriveNextStepMessage(
                  bestStreak: bestStreak,
                  currentStreak: currentStreak,
                  currentPercent: currentPercent,
                  cohortPercent: cohortPercent,
                ))
            : (nextRankUpMessage ??
                percentMessage ??
                nextCohortRankUpMessage ??
                _deriveNextStepMessage(
                  bestStreak: bestStreak,
                  currentStreak: currentStreak,
                  currentPercent: currentPercent,
                  cohortPercent: cohortPercent,
                ));
        final baseEncouragement = _deriveEncouragementMessage(
          bestStreak: bestStreak,
          currentStreak: currentStreak,
          bestPercent: bestPercent,
        );
        _streakEncouragementMessage = [
          baseEncouragement,
          cohortMessage,
        ].whereType<String>().where((text) => text.isNotEmpty).join('\n');
        _isLoadingStreakInsights = false;
      });
    } catch (e, st) {
      debugPrint('streak insight error: $e');
      debugPrintStack(stackTrace: st);
      if (!mounted) return;
      setState(() {
        _streakBestPercent = null;
        _streakCurrentPercent = null;
        _streakCohortPercent = null;
        _streakNextGoal = null;
        _streakType = null;
        _streakNextStepMessage = null;
        _streakEncouragementMessage = null;
        _isLoadingStreakInsights = false;
      });
    }
  }

  Future<void> _loadProfileTitleIfNeeded() async {
    debugPrint(
