  String? _deriveStreakType({
    required int bestStreak,
    required int currentStreak,
  }) {
    if (currentStreak <= 0) return _t('リスタート待ち', 'Restarting');
    if (bestStreak <= 0) return _t('はじめたて', 'Just started');

    if (currentStreak >= 6 && currentStreak >= bestStreak) {
      return _t('爆伸び中', 'Surging');
    }

    if (currentStreak >= bestStreak) {
      return _t('更新中', 'New record pace');
    }

    if (bestStreak >= 6 && currentStreak >= 4) {
      return _t('安定型', 'Steady type');
    }

    if (currentStreak >= (bestStreak / 2).ceil()) {
      return _t('積み上げ型', 'Builder type');
    }

    return _t('追い上げ型', 'Comeback type');
  }

