  int _toInt(dynamic value) {
    if (value == null) return 0;
    if (value is int) return value;
    if (value is num) return value.toInt();
    return int.tryParse(value.toString()) ?? 0;
  }
  int? _calculateTopPercent({
    required int value,
    required List<Map<String, dynamic>> rows,
    // int minimumSampleSize = 20,
    int minimumSampleSize = 3,
  }) {
    if (value < 1 || rows.isEmpty) return null;

    final sampleSize = _toInt(rows.first['sample_size']);
    if (sampleSize < minimumSampleSize) return null;

    var higherCount = 0;
    var sameCount = 0;

    for (final row in rows) {
      final metricValue = _toInt(row['metric_value']);
      final userCount = _toInt(row['user_count']);

      if (metricValue > value) {
        higherCount += userCount;
      } else if (metricValue == value) {
        sameCount += userCount;
      }
    }

    if (sameCount <= 0) return null;

    final percentileFromTop =
        ((higherCount + (sameCount / 2)) / sampleSize) * 100;

    return percentileFromTop.ceil().clamp(1, 99);
  }

