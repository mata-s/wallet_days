  String? _buildNextCohortRankUpMessage({
    required int currentStreak,
    required List<Map<String, dynamic>> rows,
  }) {
    if (currentStreak < 1 || rows.isEmpty) return null;

    final currentPercent = _calculateTopPercent(
      value: currentStreak,
      rows: rows,
    );
    if (currentPercent == null) return null;

    int? targetPercent;
    if (currentPercent > 40) {
      targetPercent = 40;
    } else if (currentPercent > 30) {
      targetPercent = 30;
    } else if (currentPercent > 10) {
      targetPercent = 10;
    } else {
      return null;
    }

    final metricValues = rows
        .map((row) => _toInt(row['metric_value']))
        .where((value) => value > currentStreak)
        .toSet()
        .toList()
      ..sort();

    for (final candidateValue in metricValues) {
      final candidatePercent = _calculateTopPercent(
        value: candidateValue,
        rows: rows,
      );
      if (candidatePercent != null && candidatePercent <= targetPercent) {
        final needed = candidateValue - currentStreak;
        if (needed > 0) {
          return _t(
  'あと$needed回で同じ開始月の上位$targetPercent%',
  '$needed more to reach the top $targetPercent% among your cohort',
);
        }
      }
    }

    return null;
  }

